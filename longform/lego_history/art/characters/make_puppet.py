# Build a v6 puppet config from keyed parts (film-local helper; same puppet system as figmakit/assets/characters/candler).
# Finds: neck point (bottom of the neck skin) on head + torso, head scale (matching neck widths), arm tops, gesture cut ends.
# Usage: python3 make_puppet.py <dir> "<name>" xo yo xa ya xh yh  (nostub points, left side)
import sys, json, glob, os, subprocess, cv2, numpy as np
d, name = sys.argv[1], sys.argv[2]; ns = sys.argv[3:9]
K = os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../../figmakit/tools')
subprocess.run(['python3', f'{K}/nostub.py', f'{d}/torso_with_stubs.png', f'{d}/torso.png', *ns], check=True)
def load(f): return cv2.imread(f'{d}/{f}', cv2.IMREAD_UNCHANGED)
def skin(im):
    b, g, r, a = [im[..., i].astype(int) for i in range(4)]
    return (a > 200) & (r > 140) & (r > g + 12) & (g > b + 5) & (r - b > 45)
def neck(im, region):                      # lowest skin row in the centre column band of `region` (y0, y1)
    h, w = im.shape[:2]; s = skin(im); y0, y1 = region; band = s[y0:y1, int(w * 0.3):int(w * 0.7)]
    ys, xs = np.nonzero(band); yb = ys.max(); xc = xs[ys >= yb - 6].mean() + int(w * 0.3)
    # neck width 25 px above the bottom
    row = s[y0 + yb - 25, int(w * 0.3):int(w * 0.7)]; wid = row.sum()
    return [int(round(xc)), int(y0 + yb)], int(wid)
H = load('head_neutral.png'); T = load('torso.png')
hp, hw = neck(H, (int(H.shape[0] * 0.55), H.shape[0])); tp, tw = neck(T, (0, int(T.shape[0] * 0.35)))
scale = round(min(1.0, max(0.6, tw / max(hw, 1))), 3)
def top_of(f, side='top'):
    im = load(f); a = im[..., 3] > 128; ys, xs = np.nonzero(a)
    if side == 'top': y0 = ys.min(); sel = ys <= y0 + 10; return [int(xs[sel].mean()), int(y0 + 8)]
    if side == 'left': x0 = xs.min(); sel = xs <= x0 + 10; return [int(x0 + 8), int(ys[sel].mean())]
w = T.shape[1]; xo, yo = int(ns[0]), int(ns[1])
cfg = {'name': name, 'heads': {os.path.basename(f)[5:-4]: os.path.basename(f) for f in sorted(glob.glob(f'{d}/head_*.png'))},
  'head': {'pivot': hp, 'scale': scale, 'offset': [0, 0]},
  'body': {'file': 'torso.png', 'scale': 1.0, 'neck': tp, 'shoulders': {'L': [xo + 38, yo - 4], 'R': [w - xo - 38, yo - 4]}},
  'arms': {'L': {'straight': {'file': 'arm_L_down.png', 'top': top_of('arm_L_down.png'), 'elbowY': int(load('arm_L_down.png').shape[0] * 0.30), 'rest': 0.10},
                 'gestures': {}},
           'R': {'straight': {'file': 'arm_R_down.png', 'top': top_of('arm_R_down.png'), 'elbowY': int(load('arm_R_down.png').shape[0] * 0.30), 'rest': -0.10},
                 'gestures': {}}},
  'bendZone': 60}
if os.path.exists(f'{d}/arm_L_palm.png'): cfg['arms']['L']['gestures']['palm'] = {'file': 'arm_L_palm.png', 'top': top_of('arm_L_palm.png'), 'bend': 1.70, 'swing': 0.12}
if os.path.exists(f'{d}/arm_R_palm.png'): cfg['arms']['R']['gestures']['palm'] = {'file': 'arm_R_palm.png', 'top': top_of('arm_R_palm.png'), 'bend': -1.80, 'swing': -0.12}
if os.path.exists(f'{d}/arm_R_point.png'): cfg['arms']['R']['gestures']['point'] = {'file': 'arm_R_point.png', 'top': top_of('arm_R_point.png', 'left'), 'bend': -2.40, 'swing': -0.10, 'rest': -0.12}
if os.path.exists(f'{d}/arm_R_offer.png'): cfg['arms']['R']['gestures']['offer'] = {'file': 'arm_R_offer.png', 'top': top_of('arm_R_offer.png', 'left'), 'bend': -1.30, 'swing': -0.10, 'rest': -0.10}
open(f'{d}/character.js', 'w').write(f'// {name}: v6 puppet config generated by art/characters/make_puppet.py (nostub {" ".join(ns)}). Points in each PNG\'s own pixels.\nmodule.exports = ' + json.dumps(cfg, indent=1) + ';\n')
print(d, 'head pivot', hp, 'neck w', hw, '| torso neck', tp, 'w', tw, '| head scale', scale)
