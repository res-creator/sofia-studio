def new(title, note=None):
    im = Image.new('RGB', (W, H), BG); d = ImageDraw.Draw(im); lab(d, (W / 2, 80), title, fit(d, title, 60, 1700), TXT)
    if note: lab(d, (W / 2, 805), note, fit(d, note, 34, 1700), SUB)   # низ текста < 830: ниже только субтитры
    return im, d


def arrow(d, a, b, col=TXT, w=6, hs=22):
    d.line((a, b), fill=col, width=w)
    ang = math.atan2(b[1] - a[1], b[0] - a[0])
    p1 = (b[0] - hs * math.cos(ang - 0.45), b[1] - hs * math.sin(ang - 0.45))
    p2 = (b[0] - hs * math.cos(ang + 0.45), b[1] - hs * math.sin(ang + 0.45))
    d.polygon([b, p1, p2], fill=col)


def tw(d, t, sz):
    return d.textlength(t, font=F(sz))


def dashed(d, a, b, col, w=3, dash=16):
    L = math.dist(a, b); n = int(L // (dash * 2)) + 1
    for i in range(n):
        t0 = i * 2 * dash / L; t1 = min(1, (i * 2 + 1) * dash / L)
        if t0 >= 1: break
        d.line((a[0] + (b[0] - a[0]) * t0, a[1] + (b[1] - a[1]) * t0, a[0] + (b[0] - a[0]) * t1, a[1] + (b[1] - a[1]) * t1), fill=col, width=w)


def ground(d, y, x0=120, x1=1800):
    d.line((x0, y, x1, y), fill=SUB, width=4)


def tower(d, xc, ybase, h, wbase=90, col=BL, steps=5):
    """ступенчатая башня высотой h px"""
    for i in range(steps):
        w = wbase * (1 - i / steps * 0.8); y1 = ybase - h * i / steps; y0 = ybase - h * (i + 1) / steps
        d.rectangle((xc - w / 2, y0, xc + w / 2, y1), fill=col)
    d.line((xc, ybase - h, xc, ybase - h - 0), fill=col, width=4)


