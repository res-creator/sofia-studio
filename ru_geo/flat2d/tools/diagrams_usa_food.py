def fz(d, t, sz, maxw):
    """подобрать размер, но не меньше 30"""
    while sz > 30 and d.textlength(t, font=F(sz)) > maxw: sz -= 2
    if d.textlength(t, font=F(sz)) > maxw: WARN.append(f'не влезает: {t}')
    return sz

def T(d, xy, t, sz=40, col=TXT, anchor='mm', maxw=1700):
    sz = fz(d, t, sz, maxw); d.text(xy, t, font=F(sz), fill=col, anchor=anchor)
    bb = d.textbbox(xy, t, font=F(sz), anchor=anchor)
    if bb[3] > LIM or bb[1] < 20 or bb[0] < 20 or bb[2] > W - 20: WARN.append(f'вне поля: {t} {bb}')
    return bb

def new(title, note=None):
    im = Image.new('RGB', (W, H), BG); d = ImageDraw.Draw(im)
    T(d, (W / 2, 85), title, 58, TXT)
    if note: T(d, (W / 2, 790), note, 34, SUB)
    return im, d

def save(key, im, title):
    S.save(key, im, title)

def person(d, x, y, h, col):
    """пиктограмма человека: x центр, y низ ног, h рост"""
    r = h * 0.13; d.ellipse((x - r, y - h, x + r, y - h + 2 * r), fill=col)
    bw = h * 0.36; d.rounded_rectangle((x - bw / 2, y - h + 2 * r + 4, x + bw / 2, y - h * 0.38), int(bw * 0.3), fill=col)
    lw = bw * 0.38; d.rectangle((x - bw / 2 + 2, y - h * 0.42, x - bw / 2 + 2 + lw, y), fill=col); d.rectangle((x + bw / 2 - 2 - lw, y - h * 0.42, x + bw / 2 - 2, y), fill=col)

def spoon(d, x, y, s, col=TXT):
    """чайная ложка (вид сверху), x,y центр черпала"""
    d.ellipse((x - s * 0.45, y - s * 0.6, x + s * 0.45, y + s * 0.6), fill=col)
    d.rounded_rectangle((x - s * 0.1, y + s * 0.5, x + s * 0.1, y + s * 1.9), 4, fill=col)
    d.ellipse((x - s * 0.3, y - s * 0.42, x + s * 0.3, y + s * 0.4), fill=(255, 255, 255))

def arrow(d, a, b, col=SUB, w=6, head=22):
    d.line((a, b), fill=col, width=w); ang = math.atan2(b[1] - a[1], b[0] - a[0])
    p1 = (b[0] - head * math.cos(ang - 0.45), b[1] - head * math.sin(ang - 0.45)); p2 = (b[0] - head * math.cos(ang + 0.45), b[1] - head * math.sin(ang + 0.45)); d.polygon([b, p1, p2], fill=col)

def box(d, x0, y0, x1, y1, col, txt=None, sz=40, tcol=None, fill=None, lines=None):
    d.rounded_rectangle((x0, y0, x1, y1), 24, outline=col, width=5, fill=fill)
    if txt: T(d, ((x0 + x1) / 2, (y0 + y1) / 2), txt, sz, tcol or col, maxw=x1 - x0 - 40)
    if lines:
        n = len(lines); step = sz * 1.3
        for i, t in enumerate(lines): T(d, ((x0 + x1) / 2, (y0 + y1) / 2 + (i - (n - 1) / 2) * step), t, sz, tcol or col, maxw=x1 - x0 - 40)

def cross(d, x0, y0, x1, y1, col=RD, w=10): d.line((x0, y0, x1, y1), fill=col, width=w); d.line((x0, y1, x1, y0), fill=col, width=w)

# ---------- карты (данные границ johan/world.geo.json, открытые)
GEO = {f['properties']['name']: f['geometry'] for f in json.load(open('/tmp/world.geo.json'))['features']}
def rings(g): return [g['coordinates'][0]] if g['type'] == 'Polygon' else [p[0] for p in g['coordinates']]
def draw_country(d, name, box_, col, keep=None, outline=None):
    rs = [r for r in rings(GEO[name]) if keep is None or keep(r)]
    lat0 = sum(p[1] for r in rs for p in r) / sum(len(r) for r in rs); k = math.cos(math.radians(lat0))
    xs = [p[0] * k for r in rs for p in r]; ys = [p[1] for r in rs for p in r]
    x0, y0, x1, y1 = box_; sc = min((x1 - x0) / (max(xs) - min(xs)), (y1 - y0) / (max(ys) - min(ys)))
    ox = (x0 + x1) / 2 - sc * (max(xs) + min(xs)) / 2; oy = (y0 + y1) / 2 + sc * (max(ys) + min(ys)) / 2
    P = lambda p: (ox + sc * p[0] * k, oy - sc * p[1])
    for r in rs: d.polygon([P(p) for p in r], fill=col, outline=outline)
    return P, rs
CONUS = lambda r: all(-126 < p[0] < -66 and 24 < p[1] < 50 for p in r)

def inside(pt, rs):
    x, y = pt; c = False
    for r in rs:
        for i in range(len(r)):
            (x1, y1), (x2, y2) = r[i], r[i - 1]
            if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1: c = not c
    return c

