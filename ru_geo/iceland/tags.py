def tagged(name, text):
    for n, phrase, tag in TAGS:
        if n != name: continue
        i = text.find(phrase)
        if i < 0: raise SystemExit(f'tags: «{phrase}» не найдено в {name}')
        text = text[:i] + tag + ' ' + text[i:]
    return text
