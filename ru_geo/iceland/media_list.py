import hashlib
from sources import pv, pp, wk
MEDIA = {}

def _reg(kind, ref, what, place):
    k = f'{kind}{ref}' if isinstance(ref, int) else 'w_' + hashlib.md5(ref.encode()).hexdigest()[:8]
    if k not in MEDIA: MEDIA[k] = dict(v=pv, p=pp, w=wk)[kind](ref, what, place)
    return k

def V(i, what, place='без привязки к месту', ss=0, **kw): return dict(m=_reg('v', i, what, place), ss=ss, **kw)
def P(i, what, place='без привязки к месту', kb=None, **kw): return dict(m=_reg('p', i, what, place), kb=kb or KB, **kw)
def W(ref, what, place, kb=None, **kw): return dict(m=_reg('w', ref, what, place), kb=kb or KB, **kw)
def M(name, **kw): return dict(map=name, **kw)

